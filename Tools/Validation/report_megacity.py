"""Present frozen measurements; never rerun generation or measurement."""
import html
import json
from pathlib import Path
from analyze_megacity import BASE

MODELS = ["Airport_01", "Skyscraper_02", "Church_01", "CityHall_01", "Football_01"]
PRESETS = ["Performance", "Balanced", "Quality"]


def load(phase, model, preset, suffix=""):
    return json.loads((BASE / phase / "analysis" / f"{model}_{preset}{suffix}.json").read_text())


def build():
    summary, sections, markdown = [], [], []
    for model in MODELS:
        for preset in PRESETS:
            before, after = load("baseline", model, preset), load("fixed", model, preset)
            corners_before = load("baseline", model, preset, "_boundaries")
            corners_after = load("fixed", model, preset, "_boundaries")
            levels = after["levels"][1:]
            source = after["sourceTriangles"]
            counts = " → ".join(f"{l['triangles']:,}" for l in levels)
            reduction = 100 * (1 - levels[-1]["triangles"] / source)
            lost = max(l["maxCoverageLostPct"] for l in levels)
            lost_before = max(l["maxCoverageLostPct"] for l in before["levels"][1:])
            added = max(l["maxCoverageAddedPct"] for l in levels)
            changed = max(l["maxDepthChangedPct"] for l in levels)
            moved = max(l["missingCorners"] for l in corners_after)
            moved_before = max(l["missingCorners"] for l in corners_before)
            components = [l["componentDelta"] for l in levels]
            limited = sum(not all(l["actualTargetsMet"]) for l in levels)
            core_seconds = sum(l["milliseconds"] for l in levels) / 1000
            row = {
                "model": model, "preset": preset, "sourceTriangles": source,
                "lodTriangles": [l["triangles"] for l in levels], "deepestReductionPct": reduction,
                "maxCoverageLostPctBefore": lost_before, "maxCoverageLostPctAfter": lost,
                "maxCoverageAddedPctAfter": added, "maxDepthChangedPctAfter": changed,
                "missingBoundaryCornersBefore": moved_before, "missingBoundaryCornersAfter": moved,
                "componentDeltas": components, "levelsAboveRequestedTarget": limited,
                "coreGenerationSeconds": core_seconds
            }
            summary.append(row)
            title = model + " / " + preset
            summary_row = (
                f"<tr><td><a href='#{model}_{preset}'>{title}</a></td><td>{source:,}</td><td>{counts}</td>"
                f"<td>{reduction:.1f}%</td><td>{lost_before:.2f}% → {lost:.2f}%<br>added {added:.2f}%<br>depth {changed:.2f}%</td>"
                f"<td>{moved_before} → {moved}</td><td>{limited}/{len(levels)}</td><td>{core_seconds:.2f}s</td></tr>"
            )
            markdown.append(f"| {model} | {preset} | {source:,} | {counts} | {reduction:.1f}% | "
                            f"{lost_before:.2f}% → {lost:.2f}% | {added:.2f}% | {moved_before} → {moved} | {limited}/{len(levels)} |")
            sections.append((summary_row,
                f"<section id='{model}_{preset}'><h2>{title}</h2>"
                f"<p>LOD0 → lower levels left to right. Four views, fixed source framing. "
                f"Source connected-component deltas by generated level: {html.escape(str(components))}.</p>"
                f"<h3>Before</h3><a href='baseline/analysis/{model}_{preset}.png'>"
                f"<img loading='lazy' src='baseline/analysis/{model}_{preset}.png'></a>"
                f"<h3>After</h3><a href='fixed/analysis/{model}_{preset}.png'>"
                f"<img loading='lazy' src='fixed/analysis/{model}_{preset}.png'></a></section>"))
    (BASE / "summary.json").write_text(json.dumps(summary, indent=2))
    table_head = ("| Model | Preset | LOD0 tris | LOD1 → last tris | Last reduction | Worst coverage loss, before → after | "
                  "Worst added coverage after | Missing boundary corners, before → after | Levels above target |\n"
                  "|---|---|---:|---|---:|---:|---:|---:|---:|\n")
    (BASE / "summary.md").write_text(table_head + "\n".join(markdown) + "\n", encoding="utf-8")
    page = """<!doctype html><meta charset="utf-8"><title>ComplexLODs — MegaCity validation</title>
<style>body{font:16px system-ui;max-width:1500px;margin:36px auto;padding:0 24px;background:#f8fafb;color:#172b37}
table{border-collapse:collapse;width:100%;font-size:14px}td,th{padding:10px;border-bottom:1px solid #ccd8df;text-align:left}
section{margin-top:60px}img{width:100%;border:1px solid #ccd8df}a{color:#00675c}p{line-height:1.55;max-width:1050px}
code{background:#e3e9ec;padding:3px}h1{font-size:32px}</style>
<h1>ComplexLODs — MegaCity validation</h1>
<p>Five complete prefabs, all three presets, all 50 generated levels. Generated by the real Unity importer,
profile and LOD generator. Child transforms, renderer assignments, material slots and small-mesh reuse are checked.
The saved review prefabs are under <code>Assets/ComplexLODs/Generated/Audit/fixed</code>.</p>
<p>These are geometry-only diagnostic renders, not Unity screenshots: opaque double-sided surfaces, flat lighting,
and colors by material slot. They do not test texture appearance, transparency, runtime transitions or every possible
self-intersection. Images use four fixed orthographic views at 320 × 320 pixels per tile. Coverage loss is the
percentage of source-covered pixels absent from a generated level. The summary takes the worst view and level.</p>
<p>Added coverage measures output pixels outside the source coverage, also relative to source-covered pixels.
Depth change measures common pixels whose nearest visible surface moved by more than 0.1% of the source
bounding-box diagonal. Zero lost coverage alone is not proof of unchanged geometry.</p>
<p>Boundary corners include exterior rims and internal openings, not semantic door/window labels.
A missing corner is a source boundary turn greater than 0.1 degrees (or junction) with no output vertex within
one millionth of that renderer's diagonal, with a 0.000001 world-unit minimum.
Triangle targets remain unchanged; an unmet budget is shown rather than deleting protected geometry.
The lowest levels of different presets have different distance thresholds and are not directly equivalent.</p>
<p>The stadium prefab already contained an authored LOD1. The baseline generator incorrectly treated it as
additional source geometry. Its reference view here uses the actual authored LOD0 plus eight doors
(84,463 triangles); baseline generated levels retain that erroneous extra renderer so the defect is visible.
The corrected generator excludes the authored LOD1 from its sources.</p>
<table><thead><tr><th>Model / preset</th><th>LOD0</th><th>LOD1 → last</th><th>Last reduction</th>
<th>Worst coverage loss<br>before → after</th><th>Missing boundary corners<br>before → after</th>
<th>Levels above target</th><th>Core generation</th></tr></thead><tbody>"""
    page += "".join(row for row, _ in sections) + "</tbody></table>"
    page += "".join(section for _, section in sections)
    (BASE / "index.html").write_text(page, encoding="utf-8")


if __name__ == "__main__":
    build()
