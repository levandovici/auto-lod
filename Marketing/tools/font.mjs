// Measure text width in pixels at a given scale (6px advance per glyph - 1 trailing).
export function textWidth(str, scale) {
    return str.length * 6 * scale - scale;
}

// Draw text into img { w, h, data: RGBA Uint8Array }.
// opts: scale (default 4), color [r,g,b], align 'left'|'center'|'right',
// shadow [r,g,b] | null, spacing extra px between glyphs.
export function drawText(img, str, x, y, opts = {}) {
    const scale = opts.scale || 4;
    const [r, g, b] = opts.color || [230, 238, 255];
    const spacing = opts.spacing || scale;
    const advance = 5 * scale + spacing;
    let w = 0;
    for (const ch of str) w += (FONT[ch] ? advance : advance);
    w -= spacing;
    if (opts.align === 'center') x -= w >> 1;
    else if (opts.align === 'right') x -= w;
    if (opts.shadow) blit(img, str, x + scale, y + scale, scale, spacing, opts.shadow);
    blit(img, str, x, y, scale, spacing, [r, g, b]);
    return w;
}

function blit(img, str, x0, y0, scale, spacing, [r, g, b]) {
    const { w, h, data } = img;
    let cx = x0;
    for (const ch of str) {
        const glyph = FONT[ch] || FONT['?'];
        for (let row = 0; row < 7; row++) {
            const bits = glyph[row];
            for (let col = 0; col < 5; col++) {
                if (!(bits & (1 << (4 - col)))) continue;
                for (let sy = 0; sy < scale; sy++) {
                    const py = y0 + row * scale + sy;
                    if (py < 0 || py >= h) continue;
                    for (let sx = 0; sx < scale; sx++) {
                        const px = cx + col * scale + sx;
                        if (px < 0 || px >= w) continue;
                        const i = (py * w + px) * 4;
                        data[i] = r; data[i + 1] = g; data[i + 2] = b; data[i + 3] = 255;
                    }
                }
            }
        }
        cx += 5 * scale + spacing;
    }
}
