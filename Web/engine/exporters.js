// Flat mesh -> file exporters, one per supported input format.
// exportMesh(mesh, ext, name) -> Uint8Array ready to download/zip.
import { meshToObj } from '../public/js/objio.js';

export function exportMesh(mesh, ext, name) {
    const enc = new TextEncoder();
    switch ((ext || 'obj').toLowerCase()) {
        case 'fbx': return enc.encode(meshToFbxAscii(mesh, name));
        case 'stl': return meshToStlBin(mesh);
        case 'glb': case 'gltf': return meshToGlb(mesh, name);
        case 'ply': return meshToPlyBin(mesh, name);
        default: return enc.encode(meshToObj(mesh, name));
    }
}

// ---------------- FBX (ASCII 7.4) ----------------
// Per-corner attribute expansion: our flat mesh stores attributes per
// vertex; FBX LayerElementNormal/UV use ByPolygonVertex mapping.
function meshToFbxAscii(mesh, name) {
    const safe = (name || 'lod').replace(/[^\w.-]/g, '_');
    const p = mesh.positions, n = mesh.normals, u = mesh.uvs;
    const nVerts = p.length / 3;

    // Flatten submeshes into polygon list + per-poly material index.
    const polys = [];
    const polyMat = [];
    mesh.submeshes.forEach((idx, s) => {
        for (let i = 0; i + 2 < idx.length; i += 3) {
            polys.push([idx[i], idx[i + 1], idx[i + 2]]);
            polyMat.push(s);
        }
    });
    const nCorners = polys.length * 3;

    const fmt = (v) => {
        const s = (+v).toPrecision(7);
        return s.includes('e') ? s : s.replace(/\.?0+$/, '') || '0';
    };
    const chunk = (arr, per) => {
        const lines = [];
        for (let i = 0; i < arr.length; i += per * 8)
            lines.push(Array.from(arr.slice(i, i + per * 8), fmt).join(','));
        return lines.join(',\n\t\t\t\t');
    };

    const vFlat = Array.from(p, fmt).join(',');
    // FBX ends each polygon by XOR-ing its last index to negative (-i-1).
    const pvi = [];
    for (const tri of polys) pvi.push(tri[0], tri[1], -tri[2] - 1);

    const layers = [];
    const layerBlocks = [];
    if (n) {
        const cn = [];
        for (const tri of polys) for (const v of tri) cn.push(n[v * 3], n[v * 3 + 1], n[v * 3 + 2]);
        layers.push(`\t\tLayerElementNormal: 0 {
\t\t\tMappingInformationType: "ByPolygonVertex"
\t\t\tReferenceInformationType: "Direct"
\t\t\tNormals: *${cn.length} {
\t\t\t\ta: ${Array.from(cn, fmt).join(',')}
\t\t\t}`);
        layerBlocks.push(`\t\t\tLayerElement:  {
\t\t\t\tType: "LayerElementNormal"
\t\t\t\tTypedIndex: 0
\t\t\t}`);
    }
    if (u) {
        const cu = [];
        for (const tri of polys) for (const v of tri) cu.push(u[v * 2], u[v * 2 + 1]);
        layers.push(`\t\tLayerElementUV: 0 {
\t\t\tMappingInformationType: "ByPolygonVertex"
\t\t\tReferenceInformationType: "Direct"
\t\t\tUV: *${cu.length} {
\t\t\t\ta: ${Array.from(cu, fmt).join(',')}
\t\t\t}`);
        layerBlocks.push(`\t\t\tLayerElement:  {
\t\t\t\tType: "LayerElementUV"
\t\t\t\tTypedIndex: 0
\t\t\t}`);
    }
    const nSubs = mesh.submeshes.length;
    layers.push(`\t\tLayerElementMaterial: 0 {
\t\t\tMappingInformationType: "ByPolygon"
\t\t\tMaterials: *${polyMat.length} {
\t\t\t\ta: ${polyMat.join(',')}
\t\t\t}`);
    layerBlocks.push(`\t\t\tLayerElement:  {
\t\t\t\tType: "LayerElementMaterial"
\t\t\t\tTypedIndex: 0
\t\t\t}`);

    const GEO = 1000, MOD = 2000, MAT0 = 3000;
    const materialNodes = [], materialConns = [];
    for (let s = 0; s < nSubs; s++) {
        materialNodes.push(`\tMaterial: ${MAT0 + s}, "Material::${safe}_mat${s}", "" {
\t\t\tVersion: 102
\t\t\tShadingModel: "phong"
\t\t\tMultiLayer: 0
\t\t\tProperties70:  {
\t\t\t\tP: "DiffuseColor", "Color", "", "A",0.8,0.8,0.8
\t\t\t}
\t\t}`);
        materialConns.push(`\tC: "OO",${MAT0 + s},${GEO}`);
    }

    return `; FBX 7.4.0 project file — generated by ComplexLODs
FBXHeaderExtension:  {
\tFBXHeaderVersion: 1003
\tFBXVersion: 7400
\tCreationTimeStamp:  {
\t\tVersion: 1000
\t\tYear: 2026
\t\tMonth: 1
\t\tDay: 1
\t\tHour: 0
\t\tMinute: 0
\t\tSecond: 0
\t\tMillisecond: 0
\t}
\tCreator: "ComplexLODs"
}
GlobalSettings:  {
\tVersion: 1000
\tProperties70:  {
\t\tP: "UnitScaleFactor", "double", "Number", "",1
\t}
}
Objects:  {
\tGeometry: ${GEO}, "Geometry::${safe}", "Mesh" {
\t\tVertices: *${nVerts * 3} {
\t\t\ta: ${vFlat}
\t\t}
\t\tPolygonVertexIndex: *${nCorners} {
\t\t\ta: ${pvi.join(',')}
\t\t}
${layers.join('\n')}
\t\tLayer: 0 {
\t\t\tVersion: 100
${layerBlocks.join('\n')}
\t\t}
\t}
\tModel: ${MOD}, "Model::${safe}", "Mesh" {
\t\tVersion: 232
\t\tProperties70:  {
\t\t\tP: "Lcl Translation", "Lcl Translation", "", "A",0,0,0
\t\t\tP: "Lcl Rotation", "Lcl Rotation", "", "A",0,0,0
\t\t\tP: "Lcl Scaling", "Lcl Scaling", "", "A",1,1,1
\t\t}
\t}
${materialNodes.join('\n')}
}
Connections:  {
\tC: "OO",${GEO},${MOD}
\tC: "OO",${MOD},0
${materialConns.join('\n')}
}
`;
}

// ---------------- STL (binary) ----------------

function meshToStlBin(mesh) {
    const p = mesh.positions;
    let nTris = 0;
    for (const s of mesh.submeshes) nTris += s.length / 3;
    const out = new ArrayBuffer(84 + nTris * 50);
    const dv = new DataView(out);
    dv.setUint32(80, nTris, true);
    let o = 84;
    for (const idx of mesh.submeshes) {
        for (let i = 0; i + 2 < idx.length; i += 3) {
            const a = idx[i] * 3, b = idx[i + 1] * 3, c = idx[i + 2] * 3;
            const ux = p[b] - p[a], uy = p[b + 1] - p[a + 1], uz = p[b + 2] - p[a + 2];
            const vx = p[c] - p[a], vy = p[c + 1] - p[a + 1], vz = p[c + 2] - p[a + 2];
            let nx = uy * vz - uz * vy, ny = uz * vx - ux * vz, nz = ux * vy - uy * vx;
            const l = Math.hypot(nx, ny, nz) || 1;
            dv.setFloat32(o, nx / l, true); dv.setFloat32(o + 4, ny / l, true); dv.setFloat32(o + 8, nz / l, true);
            for (const v of [a, b, c]) {
                dv.setFloat32(o + 12, p[v], true);
                dv.setFloat32(o + 16, p[v + 1], true);
                dv.setFloat32(o + 20, p[v + 2], true);
                o += 12;
            }
            dv.setUint16(o, 0, true);
            o += 2;
        }
    }
    return new Uint8Array(out);
}

// ---------------- GLB ----------------

function meshToGlb(mesh, name) {
    const p = mesh.positions;
    const chunks = [];
    const views = [];
    const accessors = [];
    let binLen = 0;
    const push = (arr) => {
        const pad = (4 - (binLen % 4)) % 4;
        if (pad) { chunks.push(new Uint8Array(pad)); binLen += pad; }
        views.push({ buffer: 0, byteOffset: binLen, byteLength: arr.byteLength });
        chunks.push(new Uint8Array(arr.buffer, arr.byteOffset, arr.byteLength));
        binLen += arr.byteLength;
        return views.length - 1;
    };
    const vPos = push(p);
    let mn = [Infinity, Infinity, Infinity], mx = [-Infinity, -Infinity, -Infinity];
    for (let i = 0; i < p.length; i += 3)
        for (let k = 0; k < 3; k++) {
            if (p[i + k] < mn[k]) mn[k] = p[i + k];
            if (p[i + k] > mx[k]) mx[k] = p[i + k];
        }
    accessors.push({ bufferView: vPos, componentType: 5126, count: p.length / 3, type: 'VEC3', min: mn, max: mx });
    const posAcc = accessors.length - 1;
    let nAcc = -1, uAcc = -1;
    if (mesh.normals) {
        accessors.push({ bufferView: push(mesh.normals), componentType: 5126, count: mesh.normals.length / 3, type: 'VEC3' });
        nAcc = accessors.length - 1;
    }
    if (mesh.uvs) {
        accessors.push({ bufferView: push(mesh.uvs), componentType: 5126, count: mesh.uvs.length / 2, type: 'VEC2' });
        uAcc = accessors.length - 1;
    }
    const primitives = [];
    for (const idx of mesh.submeshes) {
        accessors.push({ bufferView: push(idx), componentType: 5125, count: idx.length, type: 'SCALAR' });
        const attributes = { POSITION: posAcc };
        if (nAcc >= 0) attributes.NORMAL = nAcc;
        if (uAcc >= 0) attributes.TEXCOORD_0 = uAcc;
        primitives.push({ attributes, indices: accessors.length - 1, mode: 4 });
    }
    const gltf = {
        asset: { version: '2.0', generator: 'ComplexLODs' },
        scene: 0, scenes: [{ nodes: [0], name: name || 'lod' }],
        nodes: [{ mesh: 0, name: name || 'lod' }],
        meshes: [{ primitives }],
        accessors, bufferViews: views,
        buffers: [{ byteLength: binLen }]
    };
    if (mesh.materials && mesh.materials.length) {
        gltf.materials = mesh.materials.map(n => ({ name: n || 'sub' }));
        primitives.forEach((pr, i) => { if (i < gltf.materials.length) pr.material = i; });
    }
    let json = new TextEncoder().encode(JSON.stringify(gltf));
    const jpad = (4 - (json.length % 4)) % 4;
    if (jpad) {
        const j2 = new Uint8Array(json.length + jpad).fill(0x20);
        j2.set(json); json = j2;
    }
    const binParts = [];
    let bl = 0;
    for (const c of chunks) { binParts.push(c); bl += c.length; }
    const bpad = (4 - (bl % 4)) % 4;
    if (bpad) { binParts.push(new Uint8Array(bpad)); bl += bpad; }

    const total = 12 + 8 + json.length + 8 + bl;
    const out = new Uint8Array(total);
    const dv = new DataView(out.buffer);
    dv.setUint32(0, 0x46546c67, true); dv.setUint32(4, 2, true); dv.setUint32(8, total, true);
    dv.setUint32(12, json.length, true); dv.setUint32(16, 0x4e4f534a, true);
    out.set(json, 20);
    let o = 20 + json.length;
    dv.setUint32(o, bl, true); dv.setUint32(o + 4, 0x004e4942, true);
    o += 8;
    for (const c of binParts) { out.set(c, o); o += c.length; }
    return out;
}

// ---------------- PLY (binary little-endian) ----------------

function meshToPlyBin(mesh, name) {
    const p = mesh.positions, n = mesh.normals, u = mesh.uvs;
    const nVerts = p.length / 3;
    let nFaces = 0;
    for (const s of mesh.submeshes) nFaces += s.length / 3;
    let header = `ply\nformat binary_little_endian 1.0\ncomment ComplexLODs ${name || 'lod'}\nelement vertex ${nVerts}\nproperty float x\nproperty float y\nproperty float z\n`;
    if (n) header += 'property float nx\nproperty float ny\nproperty float nz\n';
    if (u) header += 'property float s\nproperty float t\n';
    header += `element face ${nFaces}\nproperty list uchar int vertex_indices\nend_header\n`;

    const headBytes = new TextEncoder().encode(header);
    const stride = 12 + (n ? 12 : 0) + (u ? 8 : 0);
    const out = new Uint8Array(headBytes.length + nVerts * stride + nFaces * 13);
    out.set(headBytes, 0);
    const dv = new DataView(out.buffer);
    let o = headBytes.length;
    for (let i = 0; i < nVerts; i++) {
        dv.setFloat32(o, p[i * 3], true); dv.setFloat32(o + 4, p[i * 3 + 1], true); dv.setFloat32(o + 8, p[i * 3 + 2], true);
        o += 12;
        if (n) { dv.setFloat32(o, n[i * 3], true); dv.setFloat32(o + 4, n[i * 3 + 1], true); dv.setFloat32(o + 8, n[i * 3 + 2], true); o += 12; }
        if (u) { dv.setFloat32(o, u[i * 2], true); dv.setFloat32(o + 4, u[i * 2 + 1], true); o += 8; }
    }
    for (const idx of mesh.submeshes) {
        for (let i = 0; i + 2 < idx.length; i += 3) {
            dv.setUint8(o, 3);
            dv.setInt32(o + 1, idx[i], true);
            dv.setInt32(o + 5, idx[i + 1], true);
            dv.setInt32(o + 9, idx[i + 2], true);
            o += 13;
        }
    }
    return out;
}
